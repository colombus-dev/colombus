#!/bin/bash
set -euo pipefail

if [ -z "${FLINK_DB_USERNAME:-}" ] || [ -z "${FLINK_DB_PASSWORD:-}" ]; then
    echo "FLINK_DB_USERNAME/FLINK_DB_PASSWORD not set, skipping flink_reader role"
    exit 0
fi

psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" <<-EOSQL
    CREATE ROLE "$FLINK_DB_USERNAME" LOGIN PASSWORD '$FLINK_DB_PASSWORD';
    GRANT CONNECT ON DATABASE "$POSTGRES_DB" TO "$FLINK_DB_USERNAME";
    GRANT USAGE ON SCHEMA public TO "$FLINK_DB_USERNAME";
    ALTER DEFAULT PRIVILEGES FOR ROLE "$POSTGRES_USER" IN SCHEMA public GRANT SELECT ON TABLES TO "$FLINK_DB_USERNAME";
EOSQL
